-- ===================================================================
-- SCRIPT DE BANCO DE DADOS COMPLETO E UNIFICADO PARA AYMORÉ FINANCIAMENTOS
-- ===================================================================
-- Este script foi projetado para preparar o seu banco de dados Supabase
-- para receber as solicitações de simulação de financiamento e contato
-- provenientes do site oficial de forma 100% segura e resiliente.
--
-- CARACTERÍSTICAS DESTA SOLUÇÃO:
-- 1. Suporte Híbrido (Português & Inglês): As colunas suportam ambas as 
--    nomenclaturas para garantir que as bibliotecas e requisições do 
--    SDK funcionem perfeitamente.
-- 2. Multi-Tabelas: Cria tanto a tabela principal "contatos" quanto a
--    tabela alternativa "leads" para tolerar qualquer desvio de configuração.
-- 3. Resiliência a Nulos: Apenas CPF e E-mail são obrigatórios (NOT NULL),
--    evitando que preenchimentos opcionais quebrem a inserção.
-- ===================================================================

-- 1. CRIAÇÃO DA TABELA PRINCIPAL 'contatos'
CREATE TABLE IF NOT EXISTS public.contatos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    
    -- Colunas em Português
    nome text,
    cpf text NOT NULL,
    email text NOT NULL,
    telefone text,
    assunto text DEFAULT 'Atendimento Geral',
    mensagem text DEFAULT '',
    
    -- Colunas em Inglês (Garante compatibilidade total com o SDK)
    name text,
    phone text,
    subject text DEFAULT 'Atendimento Geral',
    message text DEFAULT '',
    
    -- Data de criação do registro
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Adiciona comentários úteis nas colunas da tabela contatos
COMMENT ON TABLE public.contatos IS 'Tabela principal de contatos e leads recebidos pelo portal Aymoré Financiamentos';
COMMENT ON COLUMN public.contatos.cpf IS 'CPF ou CNPJ do cliente titular';
COMMENT ON COLUMN public.contatos.email IS 'E-mail de contato do cliente';


-- 2. CRIAÇÃO DA TABELA ALTERNATIVA 'leads'
CREATE TABLE IF NOT EXISTS public.leads (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    
    -- Colunas em Português
    nome text,
    cpf text NOT NULL,
    email text NOT NULL,
    telefone text,
    assunto text DEFAULT 'Atendimento Geral',
    mensagem text DEFAULT '',
    
    -- Colunas em Inglês
    name text,
    phone text,
    subject text DEFAULT 'Atendimento Geral',
    message text DEFAULT '',
    
    -- Data de criação do registro
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Adiciona comentários úteis nas colunas da tabela leads
COMMENT ON TABLE public.leads IS 'Tabela de contingência/leads recebidos pelo portal Aymoré Financiamentos';


-- 3. SEGURANÇA E POLÍTICAS DE ACESSO (RLS - Row Level Security)
-- Por padrão, o Supabase ativa RLS para novas tabelas. Isso impede que o seu site envie
-- leads sem que as políticas apropriadas estejam configuradas.
-- Abaixo, fornecemos duas formas de configurar:

-- OPÇÃO A (Recomendada para produção com RLS ativo):
-- Permite que usuários não autenticados (públicos) apenas INSERÇÃO de dados na tabela.
-- Eles NÃO poderão ler, atualizar ou excluir leads de outros usuários.
ALTER TABLE public.contatos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.leads ENABLE ROW LEVEL SECURITY;

-- Remove políticas antigas se já existirem para evitar conflitos
DROP POLICY IF EXISTS "Permitir inserções anônimas em contatos" ON public.contatos;
DROP POLICY IF EXISTS "Permitir inserções anônimas em leads" ON public.leads;

-- Cria políticas seguras de inserção anônima
CREATE POLICY "Permitir inserções anônimas em contatos" 
ON public.contatos 
FOR INSERT 
TO anon 
WITH CHECK (true);

CREATE POLICY "Permitir inserções anônimas em leads" 
ON public.leads 
FOR INSERT 
TO anon 
WITH CHECK (true);


-- OPÇÃO B (Alternativa de desenvolvimento rápido - Desativa o RLS totalmente):
-- Caso queira pular as políticas de segurança acima durante testes rápidos,
-- basta descomentar as duas linhas abaixo e executá-las:
-- ALTER TABLE public.contatos DISABLE ROW LEVEL SECURITY;
-- ALTER TABLE public.leads DISABLE ROW LEVEL SECURITY;


-- 4. ATUALIZAR O CACHE DE ESQUEMAS DO SUPABASE (IMPACTANTE E MANDATÓRIO)
-- Quando tabelas novas são criadas pelo SQL Editor, a API do Supabase (PostgREST)
-- pode demorar a recarregar o cache interno, gerando o erro "relation does not exist".
-- A notificação abaixo força o recarregamento instantâneo da estrutura:
NOTIFY pgrst, 'reload schema';

-- ===================================================================
-- FIM DO SCRIPT - EXECUTE COM SUCESSO NO SEU SUPABASE!
-- ===================================================================
